CATALOG = [{"name": name, "group": group, "description": description, "keywords": keywords.split("|")} for group, items in GROUPS for name, description, keywords in items]
NAMES = [item["name"] for item in CATALOG]


def suggest_departments(filename, content=""):
    haystack = (filename + "\n" + content[:60000]).casefold()
    links = []
    for item in CATALOG:
        found = [word for word in item["keywords"] if word.casefold() in haystack]
        if found:
            links.append({"name": item["name"], "evidence": "关键词：" + "、".join(found[:3])})
    return {"status": "pending", "method": "local-keywords", "links": links[:12], "note": "仅检查文件名与文字前60000字符，最多建议12科；不是诊断或就诊分流，可能漏分、错分，请核对。"}


def validate_routing(raw):
    if not isinstance(raw, dict) or not isinstance(raw.get("links"), list) or len(raw["links"]) > 12:
        raise AppError("科室关联格式无效，最多选择 12 个")
    names = set()
    links = []
    for item in raw["links"]:
        if not isinstance(item, dict):
            raise AppError("科室关联格式无效")
        name = choice(item.get("name"), NAMES, "科室")
        if name in names:
            raise AppError("科室不能重复")
        names.add(name)
        links.append({"name": name, "evidence": text(item.get("evidence", ""), "分类依据", 500)})
    return {"status": choice(raw.get("status", "pending"), ("pending", "confirmed"), "分类状态"), "method": choice(raw.get("method", "manual"), ("manual", "local-keywords", "ai-reviewed"), "分类方法"), "links": links, "note": text(raw.get("note", ""), "分类备注", 1000)}
